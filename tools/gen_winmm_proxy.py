"""Generate the winmm.dll pass-through for the alpha DLL from the system winmm.dll.

  python -B tools/gen_winmm_proxy.py [--dll C:\\Windows\\System32\\winmm.dll] [--out src/winmm_proxy]

The alpha DLL is shipped as winmm.dll (MHW imports winmm at startup), so it
exports every winmm function, by the same name and ordinal, as a jump through
a table filled from the system winmm.dll (winmm_proxy.cpp). Writes:

  winmm_exports.def    linker exports: name=winmm_stub_N @ordinal (NONAME kept)
  winmm_stubs.asm      MASM x64 stubs: jmp [winmm_table + N*8]
  winmm_exports.inc    C++ table rows {name or nullptr, ordinal}

Only export names and ordinals are read; no Microsoft code is copied.
"""
import argparse
import struct
from pathlib import Path


def exports(path):
    data = Path(path).read_bytes()
    pe = struct.unpack_from('<I', data, 0x3C)[0]
    assert data[pe:pe + 4] == b'PE\0\0' and struct.unpack_from('<H', data, pe + 24)[0] == 0x20B, 'PE32+ image'
    sections = []
    count, optional = struct.unpack_from('<H', data, pe + 6)[0], struct.unpack_from('<H', data, pe + 20)[0]
    for i in range(count):
        at = pe + 24 + optional + 40 * i
        size, rva, raw_size, raw = struct.unpack_from('<IIII', data, at + 8)
        sections.append((rva, max(size, raw_size), raw))

    def offset(rva):
        for start, size, raw in sections:
            if start <= rva < start + size:
                return rva - start + raw
        raise ValueError(hex(rva))
    export_rva, export_size = struct.unpack_from('<II', data, pe + 24 + 112)
    d = offset(export_rva)
    base, functions, names, functions_rva, names_rva, ordinals_rva = struct.unpack_from('<IIIIII', data, d + 16)
    named = {}
    for i in range(names):
        name_rva = struct.unpack_from('<I', data, offset(names_rva) + 4 * i)[0]
        index = struct.unpack_from('<H', data, offset(ordinals_rva) + 2 * i)[0]
        end = data.index(b'\0', offset(name_rva))
        named[index] = data[offset(name_rva):end].decode('ascii')
    rows = []
    for index in range(functions):
        if struct.unpack_from('<I', data, offset(functions_rva) + 4 * index)[0] == 0:
            continue  # unused ordinal slot
        rows.append((base + index, named.get(index)))
    return rows


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--dll', default=r'C:\Windows\System32\winmm.dll')
    p.add_argument('--out', type=Path, default=Path(__file__).resolve().parents[1] / 'src' / 'winmm_proxy')
    a = p.parse_args()
    rows = exports(a.dll)
    a.out.mkdir(parents=True, exist_ok=True)
    header = '; Generated by tools/gen_winmm_proxy.py from the system winmm.dll export table.\n'
    with open(a.out / 'winmm_exports.def', 'w', newline='\r\n') as f:
        f.write(header + 'EXPORTS\n')
        for n, (ordinal, name) in enumerate(rows):
            f.write(f'    {name}=winmm_stub_{n} @{ordinal}\n' if name else f'    winmm_ordinal_{ordinal}=winmm_stub_{n} @{ordinal} NONAME\n')
    with open(a.out / 'winmm_stubs.asm', 'w', newline='\r\n') as f:
        f.write(header + '.data\nPUBLIC winmm_table\n')
        f.write(f'winmm_table QWORD {len(rows)} DUP(0)\n.code\n')
        for n in range(len(rows)):
            f.write(f'winmm_stub_{n} PROC\n    jmp QWORD PTR [winmm_table + {8 * n}]\nwinmm_stub_{n} ENDP\n')
        f.write('END\n')
    with open(a.out / 'winmm_exports.inc', 'w', newline='\r\n') as f:
        f.write('// Generated by tools/gen_winmm_proxy.py from the system winmm.dll export table.\n')
        for ordinal, name in rows:
            f.write(f'{{"{name}", {ordinal}}},\n' if name else f'{{nullptr, {ordinal}}},\n')
    print(f'{len(rows)} exports ({sum(1 for _, n in rows if not n)} by ordinal only) -> {a.out}')


if __name__ == '__main__':
    main()
